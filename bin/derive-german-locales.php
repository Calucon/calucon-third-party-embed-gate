<?php
/**
 * Derive the other German locales from the two we maintain by hand.
 *
 * WordPress has five German locales and does NOT fall back between them: a
 * site set to de_AT gets English from this plugin unless a de_AT file exists,
 * even though our de_DE fits it word for word.
 *
 *   de_DE         (du)   — maintained by hand
 *   de_DE_formal  (Sie)  — maintained by hand
 *   de_AT         (du)   — de_DE verbatim
 *   de_CH         (Sie)  — de_DE_formal, Swiss orthography
 *   de_CH_informal (du)  — de_DE, Swiss orthography
 *
 * The Swiss team's own documented workflow is exactly this: translate de_DE,
 * adapt the formal variant, then run both through a converter. Two rules make
 * up the conversion, both verified against approved WordPress core strings in
 * those locales ("Dateigrösse", "Sie dürfen «%s» nicht hochladen"):
 *
 *   - Switzerland does not use the sharp S: ß becomes ss.
 *   - Switzerland quotes with guillemets: „…“ becomes «…», no inner spaces.
 *
 * Austria's differences from standard German (Jänner, currency) live in
 * WordPress core's own date and number formats, not in strings like ours, so
 * the de_AT file is a faithful copy — and stays honest by being generated
 * rather than claimed as a separate translation.
 *
 * Derived files are overwritten on every run. Edit de_DE / de_DE_formal, never
 * these. A language pack from translate.wordpress.org overrides them anyway,
 * which is the intended end state.
 *
 * Usage: php bin/derive-german-locales.php   (bin/update-translations.sh runs it)
 *
 * @package CaluconEmbedGate
 */

$root   = dirname( __DIR__ );
$domain = 'calucon-third-party-embed-gate';

$targets = array(
	'de_AT'          => array( 'source' => 'de_DE', 'swiss' => false ),
	'de_CH'          => array( 'source' => 'de_DE_formal', 'swiss' => true ),
	'de_CH_informal' => array( 'source' => 'de_DE', 'swiss' => true ),
);

/**
 * Swiss orthography, applied to translated text only — never to a msgid, a
 * header or a reference comment.
 *
 * @param string $text Translation.
 * @return string
 */
function cg_swiss( string $text ): string {
	return str_replace( array( 'ß', '„', '“' ), array( 'ss', '«', '»' ), $text );
}

foreach ( $targets as $locale => $spec ) {
	$source = $root . '/languages/' . $domain . '-' . $spec['source'] . '.po';
	if ( ! is_readable( $source ) ) {
		fwrite( STDERR, "missing source: $source\n" );
		exit( 1 );
	}

	$lines   = explode( "\n", (string) file_get_contents( $source ) );
	$out     = array();
	$in_msgstr = false;
	$header  = true;
	$changed = 0;

	foreach ( $lines as $line ) {
		// msgmerge keeps strings that left the POT as obsolete "#~" entries so
		// they come back translated if the string returns. They are still
		// German, so Swiss orthography applies to them too — otherwise a ß
		// survives in the Swiss files and TranslationTest fails on a line
		// nobody can see in Poedit.
		$bare      = 0 === strpos( $line, '#~ ' ) ? substr( $line, 3 ) : $line;
		$is_msgstr = 0 === strpos( $bare, 'msgstr ' );
		if ( 0 === strpos( $bare, 'msgid ' ) ) {
			$in_msgstr = false;
		}
		if ( $is_msgstr ) {
			$in_msgstr = true;
		}

		// The header entry is the first msgstr; its fields are metadata.
		if ( $header && $in_msgstr && '' === trim( $line ) ) {
			$header = false;
		}

		if ( $header ) {
			$line = str_replace( '"Language: ' . $spec['source'] . '\n"', '"Language: ' . $locale . '\n"', $line );
		} elseif ( $spec['swiss'] && ( $is_msgstr || ( $in_msgstr && 0 === strpos( $bare, '"' ) ) ) ) {
			$swiss = cg_swiss( $line );
			if ( $swiss !== $line ) {
				++$changed;
			}
			$line = $swiss;
		}

		$out[] = $line;
	}

	$note = "# GENERATED by bin/derive-german-locales.php from $domain-{$spec['source']}.po —\n"
		. "# edit that file, not this one.\n";
	$body = $note . implode( "\n", $out );

	$path = $root . '/languages/' . $domain . '-' . $locale . '.po';
	file_put_contents( $path, $body );
	printf( "  %-15s ← %-13s %s\n", $locale, $spec['source'], $spec['swiss'] ? "($changed lines converted to Swiss orthography)" : '(verbatim)' );
}
